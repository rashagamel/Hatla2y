"""
Phase 3 — AI Sales Conversation Copilot.

The genuinely new piece here (Phase 1 already extracts requirements and
objections; Phase 2 already generates next-best-action messages) is tying
an INCOMING message directly to a REPLY: a customer says something, and
the system proposes what to actually type back — referencing the specific
objection/preference change just raised, using only real data (remaining
preferences, real match locations, real plan-fit text already generated by
matching.py), never inventing figures or property details.

Reuses existing modules rather than duplicating them: extraction.py for
parsing (now including Phase 3's negative-preference/engagement-signal
detection), matching.py for property alternatives, next_action.py's
_plan_fit_reason() helper for real plan text. No new matching or scoring
logic here — this module is purely about composing a reply from what
those modules already know.
"""
import json

from db import get_connection
from extraction import extract_profile, merge_profile_into_lead
from matching import match_lead_to_properties
from next_action import _plan_fit_reason, describe_plan_reason as _describe_plan


def build_conversation_reply(lead: dict, extracted: dict, matches: list) -> str:
    """Composes a natural reply acknowledging what was just said. Every
    specific claim in here traces back to a real field or a real match —
    no invented prices, plans, or property availability."""
    name_first = (lead.get("name") or "there").split(" ")[0]
    objections = extracted.get("objections") or []
    removed_locations = extracted.get("removed_locations") or []
    parts = []

    # matches also contains units that FAIL the lead's stated requirements (wrong bedrooms, plan
    # over the monthly cap, ...): matching.py ranks them lower but still returns them. Only units
    # that meet every stated requirement may be offered as alternatives or cited as an example.
    qualified = [m for m in matches if not m.get("hard_fail")]

    if "monthly_payment" in objections:
        parts.append("Absolutely, I can focus on options with a lower monthly payment.")
    elif "down_payment" in objections:
        parts.append("Understood — I'll prioritize plans with a smaller down payment.")
    elif objections:
        parts.append("Got it, I'll keep that in mind.")

    if removed_locations:
        removed_str = " and ".join(removed_locations)
        remaining = [l.strip() for l in (lead.get("preferred_locations") or "").split(",") if l.strip()]
        if remaining:
            parts.append(f"I'll also look outside {removed_str} — I have options in "
                         f"{' and '.join(remaining)} that could work.")
        else:
            # No other stated preference — offer real alternatives drawn from actual current
            # matches (never hardcoded city names), so the suggestion is always grounded in
            # inventory that genuinely exists right now.
            alt_locations = []
            for m in qualified:
                if m["location"] not in removed_locations and m["location"] not in alt_locations:
                    alt_locations.append(m["location"])
                if len(alt_locations) == 2:
                    break
            if alt_locations:
                parts.append(f"I also have a few alternatives outside {removed_str}, like "
                             f"{' and '.join(alt_locations)}, that could stay within your budget.")
                parts.append(f"Would you prefer {alt_locations[0]}" +
                             (f" or {alt_locations[1]}?" if len(alt_locations) > 1 else "?"))
            else:
                parts.append(f"Let me see what else is available outside {removed_str}.")

    if not parts:
        # No objection or preference change detected — not a conversation-copilot moment,
        # just acknowledge receipt rather than force a fabricated reply
        return None

    plan_reason = _plan_fit_reason(qualified[0]) if qualified and "monthly_payment" in objections else None
    # Only cite a specific example when (a) it's a genuine plan FIT, not a "Closest plan"
    # approximation, AND (b) the lead actually has a known monthly cap — matching.py treats
    # every plan as trivially "fitting" when no cap is set at all (nothing to violate), so
    # "plan fits" text alone doesn't guarantee this example is genuinely reassuring.
    if plan_reason and "plan fits" in plan_reason.lower() and lead.get("max_monthly_payment"):
        example = _describe_plan(plan_reason)
        if example:
            parts.insert(1, f"For example, {qualified[0]['title']} has {example}.")

    return f"Hi {name_first}! " + " ".join(parts)


def generate_conversation_reply(lead_id: int, message_text: str) -> dict:
    """Main entry point. Logs the inbound message, extracts + merges the profile
    (including Phase 3's removed-location/engagement-signal detection), logs an
    intent_signal event when applicable, re-matches against the UPDATED profile
    (so a just-removed location is already reflected), and composes a reply."""
    conn = get_connection()
    conn.execute("INSERT INTO lead_events (lead_id, event_type, payload) VALUES (?, 'message_in', ?)",
                  (lead_id, message_text))
    conn.commit()
    conn.close()

    extracted = extract_profile(message_text)
    updated_fields = merge_profile_into_lead(lead_id, extracted)

    conn = get_connection()
    lead_row = conn.execute("SELECT * FROM leads WHERE id = ?", (lead_id,)).fetchone()
    if not lead_row:
        conn.close()
        raise ValueError(f"Lead {lead_id} not found")
    lead = dict(lead_row)

    engagement_signal = extracted.get("engagement_signal")
    if engagement_signal:
        conn.execute("INSERT INTO lead_events (lead_id, event_type, payload) VALUES (?, 'intent_signal', ?)",
                      (lead_id, engagement_signal))
        conn.commit()
    conn.close()

    # Re-match against the now-updated profile — e.g. a just-removed location is
    # already excluded from consideration by the time we suggest alternatives.
    matches = match_lead_to_properties(lead_id, top_n=5)
    preview = matches[:5]
    suggested_reply = build_conversation_reply(lead, extracted, preview)

    return {
        "extracted": extracted,
        "updated_fields": updated_fields,
        "removed_preferences": {"locations": extracted.get("removed_locations") or []},
        "engagement_signal": engagement_signal,
        "objections_detected_this_message": extracted.get("objections") or [],
        "suggested_reply": suggested_reply,
        "matches_preview": preview,
    }


